"""Build benchmark/RESULTS.md: run 2 is the headline, run 1 is kept as superseded.

  python benchmark/compare_runs.py

Reads only committed files: benchmark/RESULTS_run2.md (written by metrics.py from the run-2 run files), the run-1 CSVs in
benchmark/results/, the run-2 CSVs in benchmark/results/run2/ and benchmark/results/samples_missing*.csv. It inserts a
"Runs" section (side-by-side table, per-item comparison) after the run-2 header; every number in it is computed here.
The run-1 document is kept unchanged as benchmark/RESULTS_run1.md. No scan is run and no rule is changed.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

BENCH = Path(__file__).resolve().parent
RUN1, RUN2 = BENCH / "results", BENCH / "results" / "run2"
OUT, RUN2_MD = BENCH / "RESULTS.md", BENCH / "RESULTS_run2.md"
sys.path.insert(0, str(BENCH))

import metrics as M  # noqa: E402


def rows(p: Path) -> list[dict]:
    with open(p, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def pct(k: int, n: int) -> str:
    """The same formatting as RESULTS_run2.md (metrics.rate_text)."""
    return M.rate_text(k, n, zero_rule=True)


def compare() -> dict:
    c1 = {r["category"]: r for r in rows(RUN1 / "counts.csv")}
    c2 = {r["category"]: r for r in rows(RUN2 / "counts.csv")}
    r1 = {(r["operating_point"], r["run"]): r for r in rows(RUN1 / "recall.csv")}
    r2 = {(r["operating_point"], r["run"]): r for r in rows(RUN2 / "recall.csv")}
    f1 = {(r["set"], r["kind"]): r for r in rows(RUN1 / "false_positives_rates.csv")}
    f2 = {(r["set"], r["kind"]): r for r in rows(RUN2 / "false_positives_rates.csv")}
    i1 = {r["id"]: r for r in rows(RUN1 / "items.csv")}
    i2 = {r["id"]: r for r in rows(RUN2 / "items.csv")}
    removed = rows(BENCH / "results" / "samples_missing.csv")
    after = [p for p in ("samples_missing_after_restore.csv", "samples_missing_after_run2.csv")
             if (BENCH / "results" / p).is_file()]
    removed_ids = {r["id"] for r in removed}
    kb = lambda d: {i for i, r in d.items() if r["category"] == "known_bad" and r["status"] == "scored"}  # noqa: E731
    k1, k2 = kb(i1), kb(i2)
    gains, lost = {}, {}
    for k in ("strict_hit", "lenient_hit"):
        gains[k] = {i for i in k2 if i2[i][k] == "True" and i1.get(i, {}).get(k) != "True"}
        lost[k] = {i for i in k1 if i1[i][k] == "True" and i2.get(i, {}).get(k) != "True"}
    other = [i for i in i1 if i1[i]["category"] != "known_bad"]
    other_diff = [i for i in other if any(i1[i][c] != i2.get(i, {}).get(c) for c in
                                          ("status", "label", "trust_score", "strict_hit", "lenient_hit"))]
    base2 = {r["row"]: r for r in rows(RUN2 / "baseline.csv")} if (RUN2 / "baseline.csv").is_file() else {}
    return {"c1": c1, "c2": c2, "r1": r1, "r2": r2, "f1": f1, "f2": f2, "removed": removed, "removed_ids": removed_ids,
            "after": {p: len(rows(BENCH / "results" / p)) for p in after}, "k1": k1, "k2": k2, "gains": gains,
            "lost": lost, "other": other, "other_diff": other_diff, "base2": base2,
            "fp_identical": all(f1[k][c] == f2.get(k, {}).get(c) for k in f1 for c in ("fp", "n"))}


def section(c: dict) -> str:
    kb1, kb2 = c["c1"]["known_bad"], c["c2"]["known_bad"]
    rec = lambda d, op, run: pct(int(d[(op, run)]["hits"]), int(d[(op, run)]["n"]))  # noqa: E731
    fp = lambda d, s, k: pct(int(d[(s, k)]["fp"]), int(d[(s, k)]["n"]))  # noqa: E731
    osv2 = c["base2"].get("OSV-only (MAL- lookup alone)")
    n_rm, n_ids = len(c["removed"]), len(c["removed_ids"])
    L = ["## Runs: run 2 is the headline, run 1 is superseded", "",
         "Both runs use the frozen ruleset 2026.11.08-12, the same items, the same seed and the same data snapshot; no "
         "rule was changed between them, so the test set stays not contaminated. Generated by "
         "`benchmark/compare_runs.py` from the committed result files of both runs; no number is typed by hand.", "",
         f"- **Run 1 (first run, superseded):** after extraction, Windows Defender removed extracted `.sample` files of "
         f"known-bad DataDog items. `benchmark/verify_samples.py` found **{n_rm} files missing in {n_ids} items** "
         f"(`results/samples_missing.csv`; the count of 138 quoted from the Defender protection history is not from a repository script). Those items were scored on "
         f"less code than was extracted, so run-1 known-bad recall is biased downward. Run 1 is kept unchanged in "
         f"`RESULTS_run1.md` and `results/`.",
         "- **Run 2 (headline):** `extract_datadog.py --restore-missing` restored the files (ZIP and file sha256 "
         "checked against the unchanged manifests), with a Defender exclusion for the samples folder only; "
         + "; ".join(f"`results/{p}` lists {n} problem file(s)" for p, n in c["after"].items())
         + ". Everything below this section is run 2 (`RESULTS_run2.md`, `results/run2/`).", "",
         "| measure | run 1 (superseded) | run 2 (headline) |", "|---|---|---|",
         f"| scored known-bad | {kb1['scored']} | {kb2['scored']} |",
         f"| known-bad not assessed (sample missing at scan time) | {kb1['not_assessed']} | {kb2['not_assessed']} |",
         f"| strict recall (no OSV) | {rec(c['r1'], 'strict', 'headline')} | {rec(c['r2'], 'strict', 'headline')} |",
         f"| lenient recall (no OSV) | {rec(c['r1'], 'lenient', 'headline')} | {rec(c['r2'], 'lenient', 'headline')} |",
         f"| with OSV, strict (circular) | {rec(c['r1'], 'strict', 'with_osv')} | {rec(c['r2'], 'strict', 'with_osv')} |",
         f"| OSV-only (circular) | not computed for run 1 | "
         f"{pct(int(osv2['count']), int(osv2['n'])) if osv2 else 'n/a'} |"]
    for s, k in (("known_good", "strict"), ("known_good", "lenient"), ("scary", "lenient"), ("dormant", "lenient")):
        L.append(f"| false positives, {s}, {k} | {fp(c['f1'], s, k)} | {fp(c['f2'], s, k)} |")
    L += ["", f"False-positive rates: {'identical in every set and kind' if c['fp_identical'] else 'DIFFER'} "
          f"(`false_positives_rates.csv`); {len(c['other']) - len(c['other_diff'])} of {len(c['other'])} known-good, "
          f"scary and dormant items have the same status, label, Trust score and hits in both runs.", "",
          f"Per item: every run-1 scored known-bad item is scored in run 2 ({'yes' if c['k1'] <= c['k2'] else 'NO'}); "
          f"{len(c['k2'] - c['k1'])} items are newly scored (their sample was missing at run-1 scan time). Strict hits "
          f"gained {len(c['gains']['strict_hit'])}, lost {len(c['lost']['strict_hit'])}; lenient hits gained "
          f"{len(c['gains']['lenient_hit'])}, lost {len(c['lost']['lenient_hit'])}. Hits gained in items that had "
          f"files removed: strict {len(c['gains']['strict_hit'] & c['removed_ids'])} of "
          f"{len(c['gains']['strict_hit'])}, lenient {len(c['gains']['lenient_hit'] & c['removed_ids'])} of "
          f"{len(c['gains']['lenient_hit'])}.", ""]
    return "\n".join(L)


def render() -> str:
    text = RUN2_MD.read_text(encoding="utf-8")
    head, sep, rest = text.partition("\n## ")
    return head.rstrip("\n") + "\n\n" + section(compare()) + "\n" + sep.lstrip("\n") + rest


def main(argv=None) -> int:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
