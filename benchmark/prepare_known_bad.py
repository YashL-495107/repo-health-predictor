"""One command to prepare the known-bad side of the benchmark (no scan, no scoring, test split untouched):

  python benchmark/prepare_known_bad.py --datadog-dir PATH [--samples-dir PATH] [--skip-extract]

1. runs the pre-declared DataDog extraction (extract_datadog.py; protocol section 6), unless --skip-extract; with a
   folder made by fetch_datadog_subset.py the ZIPs are read through its subset/mapping.csv (Windows-compatible names);
2. regenerates manifests/known_bad_items.csv: every known-bad item (OSV MAL- candidates whose registry code is still
   published, plus the extracted DataDog samples) with its split after the dev-overlap check and whether its code is
   present on this machine (a sample folder emptied by antivirus counts as "no code");
3. regenerates the compare_chat_ai item list (seeded, independent of any scan result);
4. prints how many items now have code.
Everything is deterministic from the manifests, the dataset commit and the seed.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "benchmark"
for p in (str(ROOT), str(BENCH)):
    if p not in sys.path:
        sys.path.insert(0, p)

import bench_items  # noqa: E402

OUT = bench_items.MAN / "known_bad_items.csv"


def has_code(item: dict, samples_root: Path) -> tuple[str, str]:
    if item.get("source") == "datadog":
        d = samples_root / item["sample_dir"]
        n = sum(1 for _ in d.rglob("*.sample")) if d.is_dir() else 0
        return ("yes", f"{n} text file(s) in {item['sample_dir']}") if n else ("no", "sample folder missing or empty")
    return ("yes", item.get("obtainable_detail", "")) if item.get("obtainable") == "yes" else \
        ("no", item.get("obtainable_detail") or "not obtainable")


def build(samples_root: Path) -> list[dict]:
    items, _moves = bench_items.v1_items()
    rows = []
    for it in sorted((i for i in items if i["category"] == "known_bad"), key=lambda i: i["id"]):
        code, detail = has_code(it, samples_root)
        rows.append({"id": it["id"], "source": it["source"], "ecosystem": it["ecosystem"], "package": it["package"],
                     "version": it["version"], "split": it["split"], "move_reason": it["move_reason"],
                     "has_code": code, "code_detail": detail[:200]})
    return rows


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Prepare the known-bad items (extraction + manifests; no scan)")
    ap.add_argument("--datadog-dir", required=True, help="local clone of DataDog/malicious-software-packages-dataset")
    ap.add_argument("--samples-dir", default=None, help="samples folder (default benchmark/samples, git-ignored)")
    ap.add_argument("--skip-extract", action="store_true", help="reuse an earlier extraction")
    a = ap.parse_args(argv)
    if a.samples_dir:
        os.environ["REPOHEALTH_SAMPLES_DIR"] = str(Path(a.samples_dir).resolve())
    import compare_chat_ai
    import extract_datadog
    import run_benchmark as RB
    samples_root = RB.samples_root()
    if not a.skip_extract:
        rc = extract_datadog.main(["--dataset", a.datadog_dir, "--samples-dir", str(samples_root)])
        if rc:
            return rc
    mapping = extract_datadog.load_mapping(Path(a.datadog_dir))
    if mapping:   # a fetched subset: ZIPs are read through <dir>/subset/mapping.csv (Windows-compatible names)
        unsafe = [m for m in mapping.values() if m.get("note")]
        print(f"DataDog subset mapping: {len(mapping)} ZIP(s) stored under Windows-compatible names"
              + (f"; {len(unsafe)} with a original path Windows cannot hold, kept: e.g. {unsafe[0]['original_path']} "
                 f"({unsafe[0]['note']})" if unsafe else ""))
    rows = build(samples_root)
    with open(OUT, "w", newline="", encoding="utf-8") as fh:
        fh.write("# Known-bad items after extraction and the dev-overlap check (no scan); has_code = code present on "
                 "this machine | generated by benchmark/prepare_known_bad.py\n")
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()) if rows else ["empty"])
        w.writeheader()
        w.writerows(rows)
    rc = compare_chat_ai.main(["select"] + (["--samples-dir", str(samples_root)] if a.samples_dir else []))
    if rc:
        return rc
    c = Counter((r["split"], r["source"], r["ecosystem"], r["has_code"]) for r in rows)
    print(f"\nwrote {OUT} ({len(rows)} known-bad items)")
    print("known-bad items with code present (split / source / ecosystem):")
    for (split, src, eco, code), n in sorted(c.items()):
        if code == "yes":
            print(f"  {split:<5} {src:<13} {eco:<5} {n}")
    test_with = sum(n for (split, _s, _e, code), n in c.items() if split == "test" and code == "yes")
    test_all = sum(n for (split, *_), n in c.items() if split == "test")
    print(f"TEST split: {test_with} of {test_all} known-bad items have code; the others are listed as not obtainable.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
